WITH TIPOS_DOCUMENTOS AS (
SELECT
    ASO_IDENTIFICACION,
    GCC_TIPO_ALFABETICO,
    ROW_NUMBER() OVER(
        PARTITION BY ASO_IDENTIFICACION
        ORDER BY ASO_FECHA_CREA DESC
    ) AS RN
FROM GRC.GCC_ASOCIADO
WHERE
    ASO_IDENTIFICACION IN :ids
)
SELECT
    ASO_IDENTIFICACION AS "ASO_IDENTIFICACION",
    GCC_TIPO_ALFABETICO AS "GCC_TIPO_ALFABETICO"
FROM TIPOS_DOCUMENTOS
WHERE 
    RN = 1 -- Si una cédula tiene varios tipos, se usa el más reciente (ASO_FECHA_CREA)